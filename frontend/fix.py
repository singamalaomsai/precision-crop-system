lines = [
    "import streamlit as st",
    "import requests",
    "import pandas as pd",
    "import matplotlib.pyplot as plt",
    "",
    "st.set_page_config(",
    "    page_title='AgriSense XAI | Streamlit',",
    "    page_icon='🌱',",
    "    layout='wide'",
    ")",
    "",
    "API_URL = 'http://127.0.0.1:8000'",
    "",
    "st.title('🌱 AgriSense XAI: Precision Crop Advisor')",
    "st.markdown('*Decoupled FastAPI Backend + XGBoost + Real-Time SHAP Attribution*')",
    "",
    "st.sidebar.header('Backend API Status')",
    "try:",
    "    h = requests.get(f'{API_URL}/health', timeout=2).json()",
    "    st.sidebar.success(f\"Online ({h['classes_loaded']} Crops Loaded)\")",
    "except Exception:",
    "    st.sidebar.error('Offline! Start FastAPI on Port 8000')",
    "",
    "st.sidebar.header('Soil & Climate Telemetry')",
    "N = st.sidebar.slider('Nitrogen (N) [ppm]', 0, 140, 90)",
    "P = st.sidebar.slider('Phosphorus (P) [ppm]', 5, 145, 42)",
    "K = st.sidebar.slider('Potassium (K) [ppm]', 5, 205, 43)",
    "temp = st.sidebar.slider('Temperature (C)', 8.0, 45.0, 20.8)",
    "hum = st.sidebar.slider('Humidity (%)', 14.0, 100.0, 82.0)",
    "ph = st.sidebar.slider('Soil pH', 3.5, 9.5, 6.5)",
    "rain = st.sidebar.slider('Rainfall (mm)', 20.0, 300.0, 202.9)",
    "",
    "payload = {",
    "    'N': N, 'P': P, 'K': K,",
    "    'temperature': temp,",
    "    'humidity': hum,",
    "    'ph': ph,",
    "    'rainfall': rain",
    "}",
    "",
    "try:",
    "    res = requests.post(f'{API_URL}/predict', json=payload, timeout=5)",
    "    if res.status_code == 200:",
    "        data = res.json()",
    "        crop = data['recommended_crop'].upper()",
    "        conf = data['confidence']",
    "        base = data['base_value']",
    "        shap_dict = data['shap_contributions']",
    "",
    "        c1, c2 = st.columns([1, 1.6])",
    "        with c1:",
    "            st.success(f'### Recommended Crop: *{crop}*')",
    "            st.metric('Model Confidence', f'{conf}%')",
    "            st.caption(f'SHAP Base Log-Odds: {base}')",
    "            df_in = pd.DataFrame(list(payload.items()), columns=['Feature', 'Value'])",
    "            st.dataframe(df_in, use_container_width=True, hide_index=True)",
    "",
    "        with c2:",
    "            st.subheader('Explainable AI: Local SHAP Feature Impact')",
    "            s_df = pd.DataFrame(list(shap_dict.items()), columns=['Feature', 'SHAP'])",
    "            s_df = s_df.sort_values(by='SHAP', ascending=True)",
    "            cols = ['#f43f5e' if v < 0 else '#10b981' for v in s_df['SHAP']]",
    "            fig, ax = plt.subplots(figsize=(7, 3.8))",
    "            ax.barh(s_df['Feature'], s_df['SHAP'], color=cols, edgecolor='black')",
    "            ax.axvline(0, color='black', linestyle='--', linewidth=0.8)",
    "            ax.set_xlabel('SHAP Log-Odds Contribution')",
    "            plt.tight_layout()",
    "            st.pyplot(fig)",
    "    else:",
    "        st.error(f'Backend Error: {res.text}')",
    "except Exception as e:",
    "    st.error(f'Cannot connect to FastAPI at {API_URL}: {e}')"
]

open("frontend/app.py", "w", encoding="utf-8").write("\n".join(lines))
print("STREAMLIT APP READY!")